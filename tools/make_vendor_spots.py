"""Recipe vendor positions -> Data_Vendors.lua (waypoint dots for vendors).

Input: raw/vendor_coords_metaforge.json, read from
metaforge.app/wow-forever/database/npcs/<slug> (the page's `coordinates`,
vmangos source): { slug: { "name": ..., "pts": [[x, y, zone, uiMapId], ...] } }.

Kept only when the position is believable:
- exactly one position, not MetaForge's placeholder page ("NPCs Database",
  Duskwood 18.3, 9.6)
- not at the very edge of the map (x or y < 5 or > 95): those are NPCs in a
  neighbouring zone projected onto the wrong map, e.g. Aerie Peak vendors
  shown at Hillsbrad's corner
- the zone matches the zone our recipe data gives for that vendor
"""
import glob
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
SRC = os.path.join(HERE, "raw", "vendor_coords_metaforge.json")
OUT = os.path.join(ROOT, "Data_Vendors.lua")
EDGE = 5


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def data_zones():
    """vendor name -> zones our recipe data lists for them"""
    zones = {}
    for path in glob.glob(os.path.join(ROOT, "Data_*.lua")):
        if path.endswith("Data_Vendors.lua"):
            continue
        text = open(path, encoding="utf-8").read()
        for m in re.finditer(r'\{ "([^"]+)", -?\d+, -?\d+, \d+, -?\d+, "([^"]*)" \}', text):
            zones.setdefault(m.group(1), set()).add(m.group(2))
    return zones


def main():
    data = json.load(open(SRC, encoding="utf-8"))
    ours = data_zones()
    spots, skipped = {}, []
    for slug, e in sorted(data.items()):
        if slug.startswith("_"):
            continue
        name, pts = e.get("name") or slug, e.get("pts") or []
        if name == "NPCs Database" or len(pts) != 1:
            skipped.append((slug, "no position" if name == "NPCs Database" or not pts else "several"))
            continue
        x, y, zone, map_id = pts[0]
        if not map_id or min(x, y) < EDGE or max(x, y) > 100 - EDGE:
            skipped.append((name, f"edge {x},{y} {zone}"))
            continue
        z = ours.get(name)
        if z and not any(d.startswith(zone) for d in z):
            skipped.append((name, f"{zone} vs {'/'.join(sorted(z))}"))
            continue
        spots[name] = (map_id, x, y, zone)
    lines = [
        "-- Generated by tools/make_vendor_spots.py from MetaForge (vmangos positions).",
        "-- Recipe vendor name -> { uiMapId, x, y, zone } for waypoint dots.",
        "local ADDON, ns = ...",
        "ns.VendorSpots = {",
    ]
    for name in sorted(spots):
        m, x, y, z = spots[name]
        lines.append(f"  [{lua_str(name)}] = {{ {m}, {x}, {y}, {lua_str(z)} }},")
    lines.append("}")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"{len(spots)} vendor positions -> Data_Vendors.lua")
    print(f"skipped {len(skipped)}:")
    for n, why in skipped:
        print("  ", n, "-", why)


if __name__ == "__main__":
    main()
